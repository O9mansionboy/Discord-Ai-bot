# Modified to accept an optional feedback_channel instead of ctx for tasks
async def execute_ai_command(command_string, feedback_channel=None, executing_guild=None):
    """
    Parses and executes a command string generated by the AI.

    Args:
        command_string: The full command string (e.g., '!say(12345, "Hello")').
        feedback_channel: (Optional) The discord.TextChannel to send feedback/errors to.
                          If None, errors are just printed.
        executing_guild: (Optional) The guild context, useful for permission checks if feedback_channel is None.
    """
    print(f"Attempting to execute command: {command_string}")
    say_match = re.match(r"!say\(\s*(\d+)\s*,\s*(['\"])(.*?)\2\s*\)", command_string, re.DOTALL)

    async def send_feedback(message):
        """Helper to send feedback if channel is available."""
        print(f"Feedback: {message}") # Always print
        if feedback_channel and isinstance(feedback_channel, discord.TextChannel):
            try:
                # Check permissions before sending feedback too
                guild_for_feedback = feedback_channel.guild
                if guild_for_feedback and guild_for_feedback.me:
                     perms = feedback_channel.permissions_for(guild_for_feedback.me)
                     if perms.send_messages:
                         await feedback_channel.send(f"AI Task Feedback: {message}")
                     else:
                          print(f"Cannot send feedback to {feedback_channel.id}, missing send perms.")
                elif not guild_for_feedback: # DM channel maybe? Unlikely for feedback here.
                    await feedback_channel.send(f"AI Task Feedback: {message}")

            except discord.Forbidden:
                 print(f"Cannot send feedback to {feedback_channel.id}, FORBIDDEN.")
            except discord.HTTPException as e:
                 print(f"Cannot send feedback to {feedback_channel.id}, HTTPException: {e}")


    if say_match:
        try:
            channel_id = int(say_match.group(1))
            message_content = say_match.group(3)

            print(f"Parsed !say: Channel ID={channel_id}, Message='{message_content}'")

            target_channel = bot.get_channel(channel_id)
            if not target_channel:
                 try:
                     target_channel = await bot.fetch_channel(channel_id)
                 except (discord.NotFound, discord.Forbidden):
                     await send_feedback(f"Tried `!say`, but channel {channel_id} not found or inaccessible.")
                     return
                 except discord.HTTPException as e:
                     await send_feedback(f"Tried `!say`, but Discord error during lookup for channel {channel_id}: {e}")
                     return

            if isinstance(target_channel, discord.TextChannel):
                # Determine the guild for permission check
                guild = target_channel.guild
                if not guild: # Should not happen for TextChannel but safety check
                     await send_feedback(f"Tried `!say` in channel {channel_id}, but couldn't determine its guild.")
                     return

                # Check bot permissions in that channel
                if guild.me: # Check if bot is still in the guild
                    perms = target_channel.permissions_for(guild.me)
                    if perms.send_messages:
                        # Handle potential message length limits
                        if len(message_content) > 2000:
                            print("Warning: AI message exceeds 2000 chars, sending truncated.")
                            await target_channel.send(message_content[:1997] + "...")
                        else:
                            await target_channel.send(message_content)
                        print(f"Successfully executed !say in channel {channel_id}")
                        # Avoid feedback for successful task-based say commands to reduce noise
                        # if feedback_channel: await send_feedback(f"Executed `!say` in channel {channel_id}.")
                    else:
                        await send_feedback(f"Tried `!say` in channel {channel_id}, but missing 'Send Messages' permission.")
                else:
                    await send_feedback(f"Tried `!say` in channel {channel_id}, but I'm no longer in that guild.")
            else:
                 await send_feedback(f"Tried `!say`, but channel {channel_id} is not a text channel.")

        except ValueError:
            await send_feedback(f"Tried `!say`, but channel ID invalid in `{command_string}`.")
        except discord.Forbidden:
             await send_feedback(f"Tried `!say` in channel {channel_id}, but Discord blocked me (Forbidden).")
        except discord.HTTPException as e:
             await send_feedback(f"Tried `!say` in channel {channel_id}, but Discord returned an error: {e}")
        except Exception as e:
            await send_feedback(f"Unexpected error executing `!say` command '{command_string}': {e}")
            # Log the full error for debugging
            import traceback
            print(f"Full Traceback for !say error:\n{traceback.format_exc()}")

    else:
        print(f"Command '{command_string}' not recognized or malformed.")
        # await send_feedback(f"Generated command I don't understand: `{command_string}`")


