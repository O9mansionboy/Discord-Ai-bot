@tasks.loop(minutes=1) # Check every 10 minutes
async def check_channel_activity():
    print("[Task Check Activity] Running check...")
    now = discord.utils.utcnow()
    for guild in bot.guilds:
        print(f"[Task Check Activity] Checking guild: {guild.name} ({guild.id})")
        if not guild.me: # Bot potentially kicked?
            print(f"[Task Check Activity] Bot not found in guild {guild.name}, skipping.")
            continue

        for channel in guild.text_channels:
             # Basic permission check first
            if not channel.permissions_for(guild.me).send_messages:
                # print(f"[Task Check Activity] Skipping #{channel.name}, no send perms.")
                continue
            if not channel.permissions_for(guild.me).view_channel:
                 # print(f"[Task Check Activity] Skipping #{channel.name}, no view perms.")
                 continue

            channel_id = channel.id
            last_msg_time = last_message_timestamps.get(channel_id)

            # If we have never seen a message, try to fetch the last one to initialize
            if last_msg_time is None:
                 try:
                     # Fetch last message to initialize timestamp if needed
                     async for last_msg in channel.history(limit=1):
                         if last_msg:
                             last_message_timestamps[channel_id] = last_msg.created_at
                             last_msg_time = last_msg.created_at
                             print(f"[Task Check Activity] Initialized last msg time for #{channel.name} to {last_msg_time.isoformat()}")
                         break # Only need the very last one
                     # If history is empty or inaccessible, record check time so we don't spam fetch
                     if last_msg_time is None:
                          last_message_timestamps[channel_id] = now
                          print(f"[Task Check Activity] Channel #{channel.name} appears empty or inaccessible, setting timestamp to now.")

                 except discord.Forbidden:
                     print(f"[Task Check Activity] Forbidden to read history in #{channel.name}, cannot check inactivity.")
                     # Mark as checked recently to avoid retrying constantly
                     last_message_timestamps[channel_id] = now
                     continue
                 except discord.HTTPException as e:
                     print(f"[Task Check Activity] HTTPException reading history in #{channel.name}: {e}")
                     # Mark as checked recently
                     last_message_timestamps[channel_id] = now
                     continue


            # Proceed if we have a timestamp
            if last_msg_time:
                time_since_last_msg = now - last_msg_time
                print(f"[Task Check Activity] Channel #{channel.name}: Last msg {time_since_last_msg} ago.")

                if time_since_last_msg > INACTIVITY_THRESHOLD:
                    # Check cooldown for conversation starters in this channel
                    last_starter_time = last_starter_sent.get(channel_id)
                    if last_starter_time and (now - last_starter_time < CONVERSATION_STARTER_COOLDOWN):
                        print(f"[Task Check Activity] Channel #{channel.name} inactive, but starter cooldown active.")
                        continue # Skip, still on cooldown

                    print(f"[Task Check Activity] Channel #{channel.name} inactive for {time_since_last_msg}. Triggering conversation starter.")
                    # --- Trigger AI for conversation starter ---
                    try:
                        # Fetch current presence data for context
                        online, idle, dnd, offline = 0, 0, 0, 0
                        if guild.member_count > 1000 and not bot.intents.members:
                             print("[WARN] Large server and missing Members Intent - presence data inaccurate.")
                        else:
                             # Ensure member list is available, might need fetch_members if cache is stale
                             # Check if chunking happened or fetch if needed
                             if guild.chunked == False and bot.intents.members:
                                 print(f"Guild {guild.name} not chunked, fetching members...")
                                 await guild.chunk() # Use fetch_members if chunk is deprecated/fails
                                 # async for member in guild.fetch_members(limit=None): pass # Alt fetch

                             for member in guild.members:
                                if not member.bot:
                                    if member.status == discord.Status.online: online += 1
                                    elif member.status == discord.Status.idle: idle += 1
                                    elif member.status == discord.Status.dnd: dnd += 1
                                    elif member.status == discord.Status.offline: offline += 1
                                    # Note: invisible treated as offline here

                        presence_summary = f"*   Online Users: {online}\n*   Idle/AFK Users: {idle}\n*   Do Not Disturb Users: {dnd}\n*   Offline Users: {offline}"

                        starter_prompt = f"""
You are an AI assistant in a Discord server named {guild.name}.
The channel #{channel.name} (ID: {channel_id}) has been inactive for over an hour.
Your goal is to generate a friendly and engaging conversation starter message appropriate for this channel.
Keep it relatively short and open-ended. Avoid anything controversial.
Consider the current server member status for tone (e.g., maybe less energetic if many are offline/DND, more engaging if many online).

**Current Server Status ({guild.name}):**
{presence_summary}

**CRITICAL:** Your response MUST be ONLY the `!say` command to send the message to the inactive channel.
Format: `!say(CHANNEL_ID, "Your conversation starter message here.")`
Example: `!say({channel_id}, "It's been quiet! What's everyone's favorite weekend activity?")`

Generate the `!say` command now.
"""
                        print(f"[Task Check Activity] Generating starter for #{channel.name} ({channel_id})...")
                        # print(f"Starter Prompt:\n{starter_prompt}") # Debugging

                        gemini_starter_messages = [
                            {"role": "user", "parts": [starter_prompt]},
                            # No priming needed here, the prompt is very specific
                        ]

                        # Use asyncio.to_thread for the blocking API call
                        response = await asyncio.to_thread(
                            gemini_model.generate_content,
                            contents=gemini_starter_messages,
                            # safety_settings=... # Add safety if needed
                        )

                        ai_response_text = ""
                        try:
                           ai_response_text = response.text
                           print(f"[Task Check Activity] Gemini Response for starter:\n{ai_response_text}")
                        except ValueError as e:
                           print(f"[Task Check Activity] Error getting text from Gemini starter response: {e}")
                           print(f"Prompt Feedback: {response.prompt_feedback}")
                           # Potentially log safety ratings if response blocked
                           continue # Skip this channel for now


                        # --- Find and Execute the !say Command ---
                        commands_to_execute = find_ai_commands(ai_response_text)
                        if commands_to_execute:
                            # We expect only one !say command here
                            command_ok = False
                            for cmd_string in commands_to_execute:
                                # Basic validation: Does the command target the correct channel?
                                say_match = re.match(r"!say\(\s*(\d+)\s*,", cmd_string)
                                if say_match and int(say_match.group(1)) == channel_id:
                                    await execute_ai_command(cmd_string, feedback_channel=None, executing_guild=guild) # No user context for feedback
                                    command_ok = True
                                    break # Execute only the first valid command
                                else:
                                    print(f"[Task Check Activity] AI generated !say command for wrong channel ({say_match.group(1) if say_match else 'N/A'}) or malformed. Expected {channel_id}. Command: {cmd_string}")

                            if command_ok:
                                # Update timestamps to prevent immediate re-trigger and mark cooldown
                                last_message_timestamps[channel_id] = now
                                last_starter_sent[channel_id] = now
                                print(f"[Task Check Activity] Conversation starter sent to #{channel.name}. Timestamps updated.")
                        else:
                            print(f"[Task Check Activity] AI did not generate a valid !say command for starter in #{channel.name}.")
                            # Optionally, could try sending a default message, but might be noisy.
                            # Record check time to prevent immediate retry on failed generation.
                            # last_message_timestamps[channel_id] = now # Careful: this resets inactivity timer


                    except Exception as e:
                        print(f"ERROR: An error occurred during conversation starter generation/execution for #{channel.name}: {e}")
                        import traceback
                        print(f"Full Traceback:\n{traceback.format_exc()}")
                        # Record check time even on error to avoid spamming failures
                        last_message_timestamps[channel_id] = now


