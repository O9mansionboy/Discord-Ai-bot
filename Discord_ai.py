# --- Command Parsing Function ---
# (Keep find_ai_commands as it was in the previous version)
def find_ai_commands(text):
    """
    Finds all command strings matching the pattern !command(...) in the text.
    Returns a list of full command strings found (e.g., ['!say(123,"Hello")']).
    Prioritizes specifically parsed !say commands.
    """
    # Use the stricter regex for reliable parsing here
    say_commands = re.findall(r"(!say\(\s*\d+\s*,\s*(['\"]).*?\2\s*\))", text, re.DOTALL)
    # This finds tuples like ('!say(123, "Hello (world)!")', '"')
    full_say_commands = [cmd[0] for cmd in say_commands]

    if full_say_commands:
        print(f"Found potential commands (refined !say): {full_say_commands}")
        return full_say_commands
    else:
        # Fallback to generic pattern if specific !say isn't found (might be less reliable)
        pattern = r"\!([a-zA-Z_]+)\((.*?)\)"
        matches = re.findall(pattern, text, re.DOTALL)
        full_commands = [f"!{name}({args})" for name, args in matches]
        if full_commands:
             print(f"Found potential commands (generic): {full_commands}")
             return full_commands
        else:
            print("No commands found.")
            return []


