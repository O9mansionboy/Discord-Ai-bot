@bot.command(name="run_ai_chat")
async def run_ai_chat(ctx, current_buffer: list):
    """Handles the interaction with the Gemini API and executes commands."""
    if not current_buffer:
        print("run_ai_chat called with empty buffer.")
        return

    # --- Get Presence Info (if in a guild) ---
    presence_summary = "N/A (Direct Message)"
    guild_name = "N/A (Direct Message)"
    if ctx.guild:
        guild = ctx.guild
        guild_name = guild.name
        # Ensure members are available (might need fetch if cache is incomplete)
        if not guild.chunked and bot.intents.members:
             print(f"Guild {guild.name} not chunked in run_ai_chat, fetching members...")
             # await guild.chunk() # Or fetch_members
             async for member in guild.fetch_members(limit=None): pass # Ensure cache fill
             print("Member fetch complete for run_ai_chat.")


        online, idle, dnd, offline = 0, 0, 0, 0
        # Recalculate counts each time; status can change quickly
        for member in guild.members:
             if not member.bot:
                 if member.status == discord.Status.online: online += 1
                 elif member.status == discord.Status.idle: idle += 1
                 elif member.status == discord.Status.dnd: dnd += 1
                 elif member.status == discord.Status.offline: offline += 1
        presence_summary = f"*   Online Users: {online}\n*   Idle/AFK Users: {idle}\n*   Do Not Disturb Users: {dnd}\n*   Offline Users: {offline}"

    # --- Construct the prompt for Gemini ---
    system_instruction = f"""
You are a helpful and conversational AI assistant integrated into a Discord chat named {bot.user.name}.
Your Discord User ID is {bot.user.id}.
When users want your attention, they might mention you like this: <@{bot.user.id}>.
You can mention users in your responses using their ID like this: <@USER_ID>.

**Current Server Context:**
*   Server Name: {guild_name}
*   Current User Statuses:
{presence_summary}
(Note: Statuses reflect the last check and might not be real-time)

**Your Goal:** Participate in the conversation naturally, answer questions, and be helpful based ONLY on the provided history and context.

**CRITICAL: Interaction Rules**
*   **ONLY use the `!say` command to send messages.** Do NOT output any conversational text outside of a `!say` command's message parameter if you intend to use the command.
*   If you want to send a message to a specific channel, you MUST use the `!say` command formatted EXACTLY as shown below within your response.
*   If your entire response is just executing an action via a command, ONLY output the command itself.
*   If you are just answering a question or making a comment *without* needing to send it to a specific channel via command, then respond with plain text (this text will be *suppressed* if *any* command is also present in your response).

**Available Commands:**

1.  `!say(channel_id, "message content")`
    *   Sends the specified "message content" (must be enclosed in double or single quotes, can be multi-line) to the Discord channel with the exact `channel_id` (must be a number).
    *   Example: `!say(1142351742143582258, "Hello everyone!")`
    *   Example: `!say(9876543210, "Hi <@1234567890>, how are you?")`

**Conversation History (most recent messages):**
The following messages form the current context. Respond based ONLY on this history. Remember the interaction rules and context.
"""

    gemini_messages = [
        {"role": "user", "parts": [system_instruction]},
        {"role": "model", "parts": ["Understood. I will analyze the conversation history and current server context. I will respond using plain text for conversation, or ONLY the `!say(channel_id, \"message content\")` command if I need to send a message to a specific channel."]}
    ]
    gemini_messages.extend(current_buffer)

    try:
        print(f"--- Sending to Gemini ({GEMINI_MODEL_NAME}) ---")
        # print(f"Messages: {gemini_messages}") # Debugging
        print("------------------------------------")

        response = await asyncio.to_thread(
             gemini_model.generate_content,
             contents=gemini_messages
        )

        ai_response_text = ""
        try:
            ai_response_text = response.text
        except ValueError:
            print("Warning: Could not extract text from Gemini response. It might have been blocked.")
            print(f"Prompt Feedback: {response.prompt_feedback}")
            if response.candidates:
                 print(f"Finish Reason: {response.candidates[0].finish_reason}")
                 print(f"Safety Ratings: {response.candidates[0].safety_ratings}")
            await ctx.send(f"Sorry {ctx.author.mention}, my response was blocked or something went wrong. (Reason: {response.prompt_feedback or 'Unknown'})")
            return

        print(f"--- Gemini Raw Response ---")
        print(ai_response_text)
        print("--------------------------")

        # --- Find Commands FIRST ---
        commands_to_execute = find_ai_commands(ai_response_text)

        # --- Decide whether to send raw text OR execute commands ---
        if commands_to_execute:
            print(f"Commands found in AI response. Executing them instead of sending raw text.")
            for cmd_string in commands_to_execute:
                # Pass ctx.channel as the feedback channel for user-invoked commands
                await execute_ai_command(cmd_string, feedback_channel=ctx.channel, executing_guild=ctx.guild)
        elif ai_response_text:
            print("No commands found in AI response. Sending raw text.")
            if len(ai_response_text) > 2000:
                await ctx.send(ai_response_text[:1997] + "...") # Truncate
            else:
                await ctx.send(ai_response_text)
        else:
            print("AI returned an empty response and no commands.")
            # await ctx.send("AI processed the input but had nothing to say or do.") # Optional


    except Exception as e:
        print(f"ERROR: An error occurred during Gemini API call or processing: {e}")
        import traceback
        print(f"Full Traceback:\n{traceback.format_exc()}")
