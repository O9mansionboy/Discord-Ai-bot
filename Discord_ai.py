@bot.event
async def on_message(message):
    if message.author == bot.user:
        return # Ignore self

    # Update last message timestamp for the channel
    now = discord.utils.utcnow()
    last_message_timestamps[message.channel.id] = now

    # --- Buffer Logic ---
    if isinstance(message.channel, discord.TextChannel): # Only buffer guild messages for now
        user_data = {
            "role": "user",
            "parts": [f"User '{message.author.name}' (ID: {message.author.id}) in Channel '{message.channel.name}' (ID: {message.channel.id}) said: {message.content}"]
        }
        message_buffer.append(user_data)
        # Optional: Trim buffer if it gets too large independent of AI runs
        # while len(message_buffer) > MAX_BUFFER_SIZE * 2: # Example limit
        #     message_buffer.pop(0)
        print(f"Buffer size: {len(message_buffer)}/{MAX_BUFFER_SIZE} | Last msg in #{message.channel.name}: {now.isoformat()}")

    ctx = await bot.get_context(message)

    # --- Trigger AI Run ---
    # Trigger if buffer is full OR if the bot is mentioned (only in guilds for mention trigger)
    trigger_ai = (len(message_buffer) >= MAX_BUFFER_SIZE) or \
                 (bot.user.mentioned_in(message) and isinstance(message.channel, discord.TextChannel))

    if trigger_ai and len(message_buffer) > 0:
        print(f"Triggering AI run (Buffer size: {len(message_buffer)}, Mentioned: {bot.user.mentioned_in(message)})")
        run_command = bot.get_command("run_ai_chat")

        if run_command:
            buffer_copy = list(message_buffer)
            message_buffer.clear() # Clear global buffer
            await ctx.invoke(run_command, current_buffer=buffer_copy)
        else:
            print("Error: Could not find the run_ai_chat command.")
            await ctx.send("Internal Error: Could not trigger AI processing.")
            message_buffer.clear() # Still clear buffer

    # Process regular bot commands (like ~$hello)
    await bot.process_commands(message)


